import type { Tool } from "@/data/tools";
import { ToolIcon } from "./toolIcons";

// ---- ToolRow -----------------------------------------------------------------
// The row of tools that sits under one department headline (see
// components/tools/DepartmentSection.tsx).
//
// It is deliberately boring: a <ul> that wraps, holding one <li> per tool. Every
// tool is drawn exactly ONCE — there are no copies, no animation and no
// JavaScript here, so whatever is in data/tools.ts is what you see.
//
// WHAT YOU SEE IN THE BROWSER
//   <ul class="tool-row">          <- flex row, wraps, centred (app/globals.css)
//     <li class="tool-item">       <- fixed-width column, e.g. 104px on phones
//       <span class="tool-icon">   <- the ash grey picture
//       <span class="tool-name">   <- the small name underneath
//     </li>
//     ...
//
// THE SIZES AND THE GAP LIVE IN CSS, NOT HERE
// -------------------------------------------
// Everything visual is a CSS variable on `.tool-row` in app/globals.css, so it
// can be changed in one place:
//   * --tool-icon-size   how big the picture is   (48px phones / 60 md / 72 lg)
//   * --tool-name-size   the size of the name     (14px / 15px / 16px)
//   * --tool-item-width  the width of one column  (104px / 120px / 136px)
//                        (this is what makes a row of 5 fit on one line on a
//                        wide screen — see max-w-4xl in app/tools/page.tsx)
//   * gap: 28px 12px     the space between items  (row-gap / column-gap;
//                        the column gap widens to 16px from md up)
//   * --tool-ash         the grey of the icons    (starts at #8c8c86)
//   * --tool-name        the colour of the names  (starts at #3d3d3a)
//
// WHY THE <li> HAS tabIndex
//   The <li> holds nothing clickable, so without tabIndex it could never receive
//   keyboard focus and the "icon turns black" effect would only work with a
//   mouse. tabIndex={0} puts each tool in the tab order so keyboard users get
//   the same feedback (and the dotted outline drawn in the CSS).
//
// HOW TO ADD OR REMOVE A TOOL
//   Do NOT edit this file. Add or remove one line in the department's `tools`
//   array in data/tools.ts — the row renders whatever is in that array.

export default function ToolRow({ tools }: { tools: Tool[] }) {
  return (
    <ul className="tool-row">
      {tools.map((tool) => (
        // tabIndex lets keyboard users reach the tool and see the hover effect
        <li key={tool.name} className="tool-item" tabIndex={0}>
          <span className="tool-icon">
            {/* ToolIcon picks the right picture for `tool.icon` (react-icons or
                a custom SVG) — see components/tools/toolIcons.tsx. */}
            <ToolIcon icon={tool.icon} className="tool-icon-svg" />
          </span>
          {/* leading-tight: if a long name has to wrap, the two lines stay close */}
          <span className="tool-name leading-tight">{tool.name}</span>
        </li>
      ))}
    </ul>
  );
}
